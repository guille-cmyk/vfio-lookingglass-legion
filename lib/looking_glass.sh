#!/usr/bin/env bash
# lib/looking_glass.sh - Looking Glass shared memory (IVSHMEM) setup & calculations

detect_display_resolution() {
    local detected=""
    for mode_file in /sys/class/drm/card*-*/modes; do
        if [[ -f "$mode_file" && -s "$mode_file" ]]; then
            detected=$(head -n 1 "$mode_file" 2>/dev/null | tr -d '\r\n')
            if [[ -n "$detected" ]]; then
                break
            fi
        fi
    done
    echo "${detected:-2560x1600}"
}

calculate_ivshmem_size() {
    local res="${1:-2560x1600}"
    case "$res" in
        1080p|1920x1080)
            echo "32"
            ;;
        1440p|2560x1440|1600p|2560x1600|wide|3440x1440)
            echo "64"
            ;;
        4k|2160p|3840x2160)
            echo "128"
            ;;
        *)
            # Custom width and height format: WxH
            if [[ "$res" =~ ^([0-9]+)x([0-9]+)$ ]]; then
                local w="${BASH_REMATCH[1]}"
                local h="${BASH_REMATCH[2]}"
                # bytes = w * h * 4 * 2 (for double buffering)
                local bytes=$(( w * h * 8 ))
                local mib=$(( (bytes + 1048575) / 1048576 ))
                # round up to next power of 2
                local p=16
                while [[ $p -lt $mib ]]; do
                    p=$(( p * 2 ))
                done
                echo "$p"
            else
                echo "64"
            fi
            ;;
    esac
}

generate_tmpfiles_conf() {
    local target_user="${1:-$USER}"
    local target_group="${2:-kvm}"
    cat <<EOF
# Generated by VFIO Looking-Glass Setup Toolkit
# Type Path Mode UID GID Age Argument
f /dev/shm/looking-glass 0660 ${target_user} ${target_group} -
EOF
}

setup_looking_glass_shm() {
    local target_user="${1:-${SUDO_USER:-$USER}}"
    local target_group="kvm"
    local conf_file="/etc/tmpfiles.d/10-looking-glass.conf"

    # Verify target group exists
    if ! getent group kvm >/dev/null 2>&1; then
        if getent group qemu >/dev/null 2>&1; then
            target_group="qemu"
        elif getent group libvirt >/dev/null 2>&1; then
            target_group="libvirt"
        fi
    fi

    log_step "Configuring Looking Glass Shared Memory (/dev/shm/looking-glass)"
    log_info "Assigning permissions to user: ${COLOR_BOLD}${target_user}${COLOR_RESET}, group: ${COLOR_BOLD}${target_group}${COLOR_RESET}"

    local content
    content=$(generate_tmpfiles_conf "$target_user" "$target_group")
    safe_write "$content" "$conf_file"

    if [[ "${DRY_RUN:-0}" -eq 1 ]]; then
        log_info "[DRY-RUN] Would create /dev/shm/looking-glass via systemd-tmpfiles"
        return 0
    fi

    local sudo_cmd=""
    if [[ $EUID -ne 0 ]]; then
        sudo_cmd="sudo"
    fi

    if command -v systemd-tmpfiles >/dev/null 2>&1; then
        $sudo_cmd systemd-tmpfiles --create "$conf_file"
        truncate -s 64M /dev/shm/looking-glass 2>/dev/null || $sudo_cmd truncate -s 64M /dev/shm/looking-glass
        log_success "/dev/shm/looking-glass initialized (64MB) via systemd-tmpfiles"
    else
        $sudo_cmd touch /dev/shm/looking-glass
        $sudo_cmd truncate -s 64M /dev/shm/looking-glass
        $sudo_cmd chown "${target_user}:${target_group}" /dev/shm/looking-glass
        $sudo_cmd chmod 0660 /dev/shm/looking-glass
        log_success "Manually initialized /dev/shm/looking-glass with 64MB"
    fi

    # Ensure user is in kvm / libvirt groups
    for grp in kvm libvirt input; do
        if getent group "$grp" >/dev/null 2>&1; then
            if ! id -nG "$target_user" | grep -qw "$grp"; then
                $sudo_cmd usermod -aG "$grp" "$target_user"
                log_info "Added user '${target_user}' to group '${grp}'"
            fi
        fi
    done
}
